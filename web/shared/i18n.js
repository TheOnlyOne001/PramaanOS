export function t(lang, key, vars) {
  const s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Translate a backend code (skill, level, band) if we know it, else show it as given.
export function term(lang, prefix, code) {
  if (!code) return "";
  const k = prefix + String(code).toLowerCase().replace(/\s+/g, "-");
  const s = (STRINGS[lang] && STRINGS[lang][k]) ?? STRINGS.en[k];
  return s ?? String(code);
}

export function matchAnswer(transcript) {
  const words = String(transcript || "").toLowerCase().replace(/[.,!?।]/g, " ").split(/\s+/).filter(Boolean);
  if (words.some((w) => NO_WORDS.includes(w))) return "decline";
  if (words.some((w) => YES_WORDS.includes(w))) return "accept";
  return null;
}
